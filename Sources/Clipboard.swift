import AppKit

struct Clip: Equatable {
    let id = UUID()
    let text: String

    var preview: String {
        let line = text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
        return String(line.prefix(72)) + (line.count > 72 ? "…" : "")
    }
}

struct History {
    static let limit = 20
    static let maximumBytes = 65_536
    private(set) var entries: [Clip] = []

    @discardableResult mutating func remember(_ text: String) -> Bool {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= Self.maximumBytes else { return false }
        if entries.first?.text == text { return false }
        let clip = entries.first(where: { $0.text == text }) ?? Clip(text: text)
        entries.removeAll(where: { $0.text == text })
        entries.insert(clip, at: 0)
        entries = Array(entries.prefix(Self.limit))
        return true
    }

    mutating func clear() { entries.removeAll() }
}

@MainActor final class ClipboardStore {
    let pasteboard: NSPasteboard
    private(set) var history = History()
    private var lastChange: Int
    var paused = false
    var onChange: (() -> Void)?
    private(set) var message = "Copy text in any app to begin."

    // Common opt-out markers used by password managers and clipboard utilities.
    static let excludedTypes = ["org.nspasteboard.ConcealedType",
                                "org.nspasteboard.TransientType",
                                "org.nspasteboard.AutoGeneratedType"]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        // Do not import whatever was on the clipboard before launch.
        lastChange = pasteboard.changeCount
    }

    func poll() {
        guard !paused else { lastChange = pasteboard.changeCount; return }
        guard pasteboard.changeCount != lastChange else { return }
        let change = pasteboard.changeCount
        lastChange = change
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            message = "Clipboard access denied. Allow clipboard access for TouchClip in System Settings, then copy new text."
            onChange?()
            return
        }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.excludedTypes) else { return }
        guard let text = pasteboard.string(forType: .string) else { return }
        // Discard a read if another app changed the clipboard in the meantime.
        guard pasteboard.changeCount == change else { return }
        if text.utf8.count > History.maximumBytes {
            message = "Skipped text larger than 64 KiB."
            onChange?()
        } else if history.remember(text) {
            message = "Tap an entry, then press ⌘V in your app."
            onChange?()
        }
    }

    func setPaused(_ value: Bool) {
        paused = value
        lastChange = pasteboard.changeCount
        message = paused ? "Recording paused. Saved entries still work." : "Recording resumed. Copy some new text."
        onChange?()
    }

    func clear() {
        history.clear()
        lastChange = pasteboard.changeCount
        message = "History cleared. Your current clipboard is unchanged."
        onChange?()
    }

    @discardableResult func restore(_ id: UUID) -> Bool {
        guard let clip = history.entries.first(where: { $0.id == id }) else { return false }
        // Prepare the item before clearing the current clipboard.
        let item = NSPasteboardItem()
        guard item.setString(clip.text, forType: .string) else { return false }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects([item])
        lastChange = pasteboard.changeCount
        if success {
            history.remember(clip.text)
            message = "Copied. Press ⌘V to paste."
        } else {
            message = "Could not write to the clipboard. Try the entry again."
        }
        onChange?()
        return success
    }
}
